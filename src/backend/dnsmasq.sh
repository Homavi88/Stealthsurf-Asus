#!/bin/sh
# DNS hijack + dnsmasq ipset integration

SS_DNSMASQ_CONF="$ADDON_SHARE_DIR/dnsmasq/stealthsurf.conf"
SS_DNSMASQ_MARKER_START="#stealthsurf start"
SS_DNSMASQ_MARKER_END="#stealthsurf end"

ss_dnsmasq_ipset_create() {
  ipset create "$SS_IPSET_PROXY_V4" hash:ip family inet timeout 86400 -exist 2>/dev/null || true
  ipset create "$SS_IPSET_BYPASS_V4" hash:ip family inet timeout 86400 -exist 2>/dev/null || true
  ipset create "$SS_IPSET_PROXY_V6" hash:ip family inet6 timeout 86400 -exist 2>/dev/null || true
  ipset create "$SS_IPSET_BYPASS_V6" hash:ip family inet6 timeout 86400 -exist 2>/dev/null || true
}

ss_dnsmasq_ipset_save() {
  mkdir -p "$(dirname "$SS_IPSET_LEARNED")"
  {
    echo "# $(date +%s)"
    ipset save "$SS_IPSET_PROXY_V4" 2>/dev/null || true
    ipset save "$SS_IPSET_BYPASS_V4" 2>/dev/null || true
  } >"$SS_IPSET_LEARNED"
}

ss_dnsmasq_ipset_restore() {
  [ -s "$SS_IPSET_LEARNED" ] || return 0
  ss_dnsmasq_ipset_create
  # Restore add lines only
  grep '^add ' "$SS_IPSET_LEARNED" 2>/dev/null | ipset -exist restore 2>/dev/null || true
}

ss_dnsmasq_build_ipset_conf() {
  local confdir conf
  confdir="$ADDON_SHARE_DIR/dnsmasq"
  conf="$SS_DNSMASQ_CONF"
  mkdir -p "$confdir"
  {
    echo "# Autogenerated by StealthSurf $(date '+%Y-%m-%d %H:%M:%S')"
    case "$SS_DNS_MODE" in
    OFF)
      echo "# DNS mode OFF — no ipset wiring"
      ;;
    BYPASS | REDIRECT)
      local setname
      if [ "$SS_DNS_MODE" = "BYPASS" ]; then
        setname="$SS_IPSET_BYPASS_V4"
      else
        setname="$SS_IPSET_PROXY_V4"
      fi
      # Domains from routing rules that are plain domain/full
      if [ -f "$SS_ROUTING_FILE" ]; then
        jq -r --arg mode "$SS_DNS_MODE" '
          (.rules // [])[] |
          select((.type // "domain") == "domain" or (.type // "") == "full") |
          .matcher // empty
        ' "$SS_ROUTING_FILE" 2>/dev/null | while read -r domain; do
          [ -n "$domain" ] || continue
          printf 'ipset=/%s/%s\n' "$domain" "$setname"
        done
      fi
      ;;
    esac
  } >"$conf"
}

ss_dnsmasq_configure() {
  local main_conf="${1:-/etc/dnsmasq.conf}"
  case "$SS_DNS_MODE" in
  OFF)
    ss_dnsmasq_cleanup "$main_conf"
    return 0
    ;;
  esac

  ss_dnsmasq_ipset_create
  ss_dnsmasq_ipset_restore
  ss_dnsmasq_build_ipset_conf

  [ -f "$main_conf" ] || return 0
  # Strip previous block
  if grep -q "$SS_DNSMASQ_MARKER_START" "$main_conf" 2>/dev/null; then
    sed "/^${SS_DNSMASQ_MARKER_START}\$/,/^${SS_DNSMASQ_MARKER_END}\$/d" "$main_conf" >"$main_conf.ss.$$" &&
      mv "$main_conf.ss.$$" "$main_conf"
  fi

  {
    echo ""
    echo "$SS_DNSMASQ_MARKER_START"
    echo "conf-file=$SS_DNSMASQ_CONF"
    if [ "$SS_DNS_MODE" = "REDIRECT" ] && [ -f "$XRAY_CONFIG_FILE" ]; then
      # Point dnsmasq at local dokodemo DNS inbound if present
      echo "no-resolv"
      echo "server=127.0.0.1#${SS_DNS_PORT}"
    fi
    echo "$SS_DNSMASQ_MARKER_END"
  } >>"$main_conf"

  ss_ok "dnsmasq configured (DNS mode=$SS_DNS_MODE)"
}

ss_dnsmasq_cleanup() {
  local main_conf="${1:-/etc/dnsmasq.conf}"
  [ -f "$main_conf" ] || return 0
  if grep -q "$SS_DNSMASQ_MARKER_START" "$main_conf" 2>/dev/null; then
    sed "/^${SS_DNSMASQ_MARKER_START}\$/,/^${SS_DNSMASQ_MARKER_END}\$/d" "$main_conf" >"$main_conf.ss.$$" &&
      mv "$main_conf.ss.$$" "$main_conf"
  fi
  ss_dnsmasq_ipset_save
}

ss_dnsmasq_restart() {
  if command -v service >/dev/null 2>&1; then
    service restart_dnsmasq >/dev/null 2>&1 || true
  else
    killall -HUP dnsmasq 2>/dev/null || true
  fi
}

ss_set_dns_mode() {
  local mode="$1"
  case "$mode" in
  OFF | BYPASS | REDIRECT) ;;
  *)
    ss_error "DNS mode must be OFF|BYPASS|REDIRECT"
    return 1
    ;;
  esac
  SS_DNS_MODE="$mode"
  ss_save_conf
  ss_dnsmasq_configure
  ss_dnsmasq_restart
  ss_ok "DNS mode set to $mode"
}
